// --- T-055: rotating/listing a consumer -------------------------------------
//
// The test that matters here is the one for BOTH SIDES. Checking only
// that the new token works proves no revocation at all — and revocation
// is the only reason someone rotates. That is why these tests go through
// the real HTTP handler (outbound.NewHandler): "401" and "200" are what
// whoever operates it will see, and a test that only called the
// authenticator would not prove the entire path agrees.

// sendVia assembles the POST /v1/messages the consumer would make,
// with the given token.
func sendVia(t *testing.T, h http.Handler, token, key string) *httptest.ResponseRecorder {
	t.Helper()
	req := httptest.NewRequest(http.MethodPost, "/v1/messages",
		strings.NewReader(`{"instancia":"lojinha","para":"5511999990000","tipo":"texto","texto":"oi"}`))
	req.Header.Set("Authorization", "Bearer "+token)
	req.Header.Set("Idempotency-Key", key)
	req.Header.Set("Content-Type", "application/json")
	rec := httptest.NewRecorder()
	h.ServeHTTP(rec, req)
	return rec
}

