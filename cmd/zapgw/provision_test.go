// --- instancia listar / mostrar ----------------------------------------------
//
// The READING slice: you could create, activate, and rotate by command,
// and until T-020 there was no way to ask "which ones exist?" nor "is
// this one up?". The only answer was opening SQLite by hand — which is
// exactly what command-based provisioning came to eliminate, and the
// fastest way for someone to write something wrong straight into the
// database.
//
// NOTHING IS DECRYPTED along this path: of the six encrypted fields,
// only whether they are recorded comes out. Decrypting only to throw it
// away would create a window with the secret in plain text in the
// memory of a command that just wanted to count instances.

func fullInstanceArgs(slug, pnid, waba, number, callback string) []string {
	return []string{
		"provisionar", "instancia",
		"--slug", slug,
		"--waba-id", waba,
		"--phone-number-id", pnid,
		"--numero-exibido", number,
		"--callback-url", callback,
	}
}

// instanceLine finds THE instance's row in the output — and
// requires there to be exactly ONE. "One row per instance" is the
// command's contract: two rows for the same instance would make whoever
// operates it count one tenant too many.
func instanceLine(t *testing.T, out, slug string) string {
	t.Helper()
	var matches []string
	for _, line := range strings.Split(out, "\n") {
		if strings.Contains(line, slug) {
			matches = append(matches, line)
		}
	}
	if len(matches) != 1 {
		t.Fatalf("%d linha(s) para a instancia %q na saida:\n%s", len(matches), slug, out)
	}
	return matches[0]
}

func TestListInstancesPrintsOneRowPerInstanceWithTheSTATE(t *testing.T) {
	// Three tenants, only one active. A listing that stopped at the
	// first row, or that swapped active for paused, would hide exactly
	// the instance that is down — and whoever operates it would walk
	// away thinking everything is up.
	vars := testEnvironment(t)
	cases := []struct {
		slug, pnid, waba, number, state string
	}{
		{"tenant-one", "PNID-LOJA", "WABA-LOJA", "5532999990001", "ativa"},
		{"clinica", "PNID-CLIN", "WABA-CLIN", "5532999990002", "pausada"},
		{"padaria", "PNID-PADA", "WABA-PADA", "5532999990003", "pausada"},
	}
	for _, c := range cases {
		var creation bytes.Buffer
		args := fullInstanceArgs(c.slug, c.pnid, c.waba, c.number, "https://consumidor.interno/hook")
		if err := dispatch(args, &creation, fakeEnvironment(vars)); err != nil {
			t.Fatalf("provisionar %q: %v", c.slug, err)
		}
	}
	// Only the smoke test activates in production; here the store plays
	// its role.
	if err := storeFromEnvironment(t, vars).ActivateInstance("tenant-one"); err != nil {
		t.Fatalf("ActivateInstance: %v", err)
	}

	var out bytes.Buffer
	if err := dispatch([]string{"instancia", "listar"}, &out, fakeEnvironment(vars)); err != nil {
		t.Fatalf("dispatch: %v", err)
	}

	for _, c := range cases {
		line := instanceLine(t, out.String(), c.slug)
		if !strings.Contains(line, c.state) {
			t.Errorf("a linha de %q nao diz %q:\n%s", c.slug, c.state, line)
		}
		if c.state == "pausada" && strings.Contains(line, " ativa") {
			t.Errorf("a linha de %q diz ativa e pausada ao mesmo tempo:\n%s", c.slug, line)
		}
		// The identifiers are what matches the row to Meta's panel.
		for _, field := range []string{c.pnid, c.waba, c.number} {
			if !strings.Contains(line, field) {
				t.Errorf("a linha de %q nao traz %q:\n%s", c.slug, field, line)
			}
		}
	}
}

