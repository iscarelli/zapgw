// labelLine finds ONE label's row (e.g., "tipo", "ig_id") in the
// output of `instancia mostrar` — the tabwriter swaps the `\t` for
// alignment spaces, so a `strings.Contains(texto, "tipo:\t...")` would
// never match.
func labelLine(t *testing.T, out, label string) string {
	t.Helper()
	for _, line := range strings.Split(out, "\n") {
		if strings.HasPrefix(strings.TrimSpace(line), label+":") {
			return line
		}
	}
	t.Fatalf("nao achei a linha %q na saida:\n%s", label, out)
	return ""
}

