// TestNoSubcommandHasAFlagCalledPin is the test T-151 requires (Do
// item 2): "pin" IS A SECRET, and a command-line argument is read by any
// local process in `ps` and shows up in every configuration dump — five
// leaks in this workspace's history. It sweeps every subcommand's `-h`
// in this section and fails if any one has a flag named EXACTLY "pin" —
// "pin-arquivo" remains allowed, because it carries the PATH, never the
// value.
func TestNoSubcommandHasAFlagCalledPin(t *testing.T) {
	flagName := regexp.MustCompile(`(?m)^\s*-pin(\s|$)`)
	for _, args := range [][]string{
		{"instancia", "registrar", "-h"},
		{"instancia", "desregistrar", "-h"},
		{"instancia", "pin", "-h"},
	} {
		var out bytes.Buffer
		_ = dispatch(args, &out, fakeEnvironment(nil))
		if flagName.MatchString(out.String()) {
			t.Errorf("%v: achei uma flag chamada EXATAMENTE \"pin\" na ajuda:\n%s", args, out.String())
		}
	}
}
