// valueFromOutput finds "field: value" in the command's output.
func valueFromOutput(t *testing.T, out, field string) string {
	t.Helper()
	for _, line := range strings.Split(out, "\n") {
		if after, found := strings.CutPrefix(strings.TrimSpace(line), field+": "); found {
			return strings.TrimSpace(after)
		}
	}
	t.Fatalf("nenhuma linha %q na saida:\n%s", field+": ", out)
	return ""
}

