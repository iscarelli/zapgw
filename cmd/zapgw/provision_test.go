// TestDispatchMenuDoesNotOpenTheScreen covers case (c), the most important of
// the three: `dispatch([]string{"menu"}, ...)` NEVER reads os.Stdin nor
// opens the menu, not even with a terminal on both sides. Without this
// test, a future refactor that swapped the `case "menu"` for a call to
// `menu(...)` would pass the other two tests (the message could still
// exist as a warning BEFORE opening the screen) and would reintroduce
// exactly what the owner rejected.
//
// The input is a CLOSED pipe: if `dispatch` tries to read from it, the
// Read returns an error (closed pipe), it never blocks the test -- and
// that is exactly the read that must not happen.
func TestDispatchMenuDoesNotOpenTheScreen(t *testing.T) {
	reader, writer, err := os.Pipe()
	if err != nil {
		t.Fatalf("os.Pipe: %v", err)
	}
	if err := writer.Close(); err != nil {
		t.Fatalf("fechar o lado de escrita do pipe: %v", err)
	}
	defer func() { _ = reader.Close() }()

	original := os.Stdin
	os.Stdin = reader
	defer func() { os.Stdin = original }()

	var out bytes.Buffer
	if err := dispatch([]string{"menu"}, &out, fakeEnvironment(testEnvironment(t))); err == nil {
		t.Fatal("dispatch([]string{\"menu\"}) nao devolveu erro")
	}
	if out.String() != "" {
		t.Errorf("dispatch([]string{\"menu\"}) escreveu na saida do menu, e nao devia escrever nada por essa via: %q", out.String())
	}
}

