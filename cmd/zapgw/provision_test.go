// 🔴 WHAT ISN'T OURS DOESN'T GET GENERATED — and the cost of that shows
// up on the ONLY read surface that exists.
//
// The command has always generated every missing secret (T-052), and
// that remains correct for `verify_token` and `segredo_entrega`, which
// belong to the gateway. For `app_secret` and `token_envio` it stopped
// being correct: they live in the CONSUMER's Meta account. If generated,
// `instancia mostrar` and the registration's response — which only say
// `cadastrado: sim|nao`, because nothing is decrypted — would start
// claiming `app_secret=sim` about a value their Meta account never saw.
// The one question the owner and the consumer can ask would go
// unanswered.
func TestProvisionInstanceONLYWithTheSlugDoesNOTDrawWhatBelongsToTheConsumerMeta(t *testing.T) {
	vars := testEnvironment(t)
	var out bytes.Buffer
	if err := dispatch([]string{"provisionar", "instancia", "--slug", "terceiro"}, &out, fakeEnvironment(vars)); err != nil {
		t.Fatalf("dispatch: %v", err)
	}

	r, err := storeFromEnvironment(t, vars).SummarizeInstance("terceiro")
	if err != nil {
		t.Fatalf("SummarizeInstance: %v", err)
	}
	registered := map[string]bool{}
	for _, c := range r.Encrypted {
		registered[c.Name] = c.Registered
	}
	for _, field := range []string{"app_secret", "token_envio"} {
		if registered[field] {
			t.Errorf("%s nasceu CADASTRADO numa instancia que espera o consumidor —"+
				" a leitura passa a dizer `sim` sobre um valor que a Meta dele nunca viu", field)
		}
	}
	// And the TWO that belong to the gateway are still generated:
	// without them the instance doesn't answer Meta's challenge nor sign
	// delivery.
	for _, field := range []string{"verify_token", "segredo_entrega"} {
		if !registered[field] {
			t.Errorf("%s NAO foi sorteado — sem ele o provisionamento nao termina (T-052)", field)
		}
	}
	// The output has to SAY it didn't generate them, otherwise
	// `app_secret=nao` looks like a defect and someone is going to "fix"
	// an instance that is correct.
	if !strings.Contains(out.String(), "NAO sorteados") {
		t.Errorf("a saida nao avisa que os segredos do consumidor nao foram sorteados:\n%s", out.String())
	}
}

