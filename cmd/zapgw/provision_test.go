func countInstancesFromEnvironment(t *testing.T, vars map[string]string) int {
	t.Helper()
	var n int
	line := storeFromEnvironment(t, vars).DB().QueryRow(`SELECT count(*) FROM instancia`)
	if err := line.Scan(&n); err != nil {
		t.Fatalf("contar instancias: %v", err)
	}
	return n
}

func TestProvisionInstanceRefusesSlugThatDoesNotBECOMEAROUTE(t *testing.T) {
	// The command is the only place where someone TYPES the slug, and
	// the slug is IMMUTABLE: rejecting it here is the only chance. The
	// damage would not show up in this terminal — it would show up at
	// Meta, when pasting /v1/inbound/{slug}, with their error message
	// pointing at the wrong place.
	cases := map[string]string{
		"com barra":      "loja/racer",
		"com espaco":     "loja racer",
		"com maiuscula":  "Lojinha",
		"hifen na ponta": "-lojinha",
		"curto demais":   "ab",
		"com query":      "loja?x=1",
	}
	for name, slug := range cases {
		t.Run(name, func(t *testing.T) {
			vars := testEnvironment(t)
			var out bytes.Buffer

			err := dispatch(instanceArgs(slug), &out, fakeEnvironment(vars))

			if !errors.Is(err, config.ErrInvalidSlug) {
				t.Fatalf("erro = %v, quero config.ErrInvalidSlug", err)
			}
			if n := countInstancesFromEnvironment(t, vars); n != 0 {
				t.Errorf("%d instancia(s) gravada(s) apesar da recusa", n)
			}
		})
	}
}

