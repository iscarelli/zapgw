// 🔴 T-079 IN ONE LINE: `--slug` is the ONLY required flag.
//
// The owner creates the instance knowing NOTHING of the consumer's Meta
// account, it is born paused and incomplete, and the command prints the
// DELIVERY PACKAGE — what he delivers, and nothing beyond that. A
// conversation that happens once, with someone he cannot reach
// afterward, cannot depend on him remembering what was missing.
func TestProvisionInstanceONLYWithTheSlugPrintsTheDeliveryPackage(t *testing.T) {
	vars := testEnvironment(t)

	var out bytes.Buffer
	if err := dispatch([]string{"provisionar", "instancia", "--slug", "terceiro"}, &out, fakeEnvironment(vars)); err != nil {
		t.Fatalf("dispatch: %v — o dono nao tem os dados da Meta do consumidor", err)
	}

	r, err := storeFromEnvironment(t, vars).SummarizeInstance("terceiro")
	if err != nil {
		t.Fatalf("SummarizeInstance: %v", err)
	}
	if r.WabaID != "" || r.PhoneNumberID != "" {
		t.Errorf("a instancia nasceu com identificacao que ninguem forneceu: waba=%q pnid=%q", r.WabaID, r.PhoneNumberID)
	}
	if r.Active {
		t.Error("a instancia nasceu ATIVA")
	}

	text := out.String()
	// Each package item, one by one: one forgotten turns into a stuck
	// consumer with no one to ask.
	for _, required := range []string{
		"PACOTE DE ENTREGA",
		"terceiro",                                       // o slug
		"https://zapgw.exemplo.test/v1/cadastro",         // para onde ele writes
		"https://zapgw.exemplo.test/v1/inbound/terceiro", // o que ele cola na Meta DELE
		"verify_token",                                   // sorteado e impresso (T-052)
		"segredo_entrega",                                //          idem
		"zapgw provisionar consumidor",                   // de onde sai o token dele
		"reabrir-cadastro",                               // o que fazer quando ele travar
	} {
		if !strings.Contains(text, required) {
			t.Errorf("o pacote de entrega nao menciona %q:\n%s", required, text)
		}
	}
	// And it says the one who registers Meta credentials is the
	// CONSUMER — otherwise the owner asks him for the values and goes
	// back to being an intermediary for someone else's credentials.
	if !strings.Contains(text, "POST /v1/cadastro") {
		t.Errorf("o pacote nao diz por onde o consumidor cadastra:\n%s", text)
	}
}

