	err := dispatch([]string{
		"instancia", "rotacionar", "--slug", "insta-loja", "--ig-id", "IGID_NOVO_SINTETICO",
	}, &out, fakeEnvironment(vars))
	if err != nil {
		t.Fatalf("dispatch: %v", err)
	}

