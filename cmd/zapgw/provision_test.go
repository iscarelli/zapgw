func TestProvisionInstancePrintsNOSecretAtAll(t *testing.T) {
	// Encrypting at rest and then printing to the terminal makes the
	// encryption decorative. The terminal output is one more place the
	// secret escapes through: it goes to the scrollback, to the ansible
	// log, and to a screenshot pasted in chat.
	//
	// THE RULE GAINED TWO NAMED EXCEPTIONS IN T-052, and they are IN
	// THIS TEST so no one reopens them by mistake: a randomly generated
	// `verify_token` and `segredo_entrega` ARE printed, because they are
	// SHARED — without the value in a person's hands, the instance is
	// born impossible to finish setting up (the whole reason is in
	// `printSharedSecrets`, proved by
	// TestInstanceCreatedWithNoSECRETINTheEnvironmentIsBornUSABLE). The rule
	// stays whole for the other two, and stays whole for all four when
	// the value CAME from the environment — which is the production
	// case.
	//
	// THE TWO CASES, and the second one was only written after a
	// MUTATION went unnoticed: with all four secrets coming from the
	// environment, the line that names the generated ones never even
	// gets printed, so a leak INSIDE it passed green. It is the trap
	// shape docs/ARMADILHAS.md records under "Testes" — the guard that
	// checks nothing and passes.
	t.Run("segredos vindos do ambiente", func(t *testing.T) {
		vars := testEnvironment(t)
		secrets := map[string]string{
			"ZAPGW_APP_SECRET":      "segredo-app-nao-pode-vazar",
			"ZAPGW_VERIFY_TOKEN":    "segredo-verify-nao-pode-vazar",
			"ZAPGW_TOKEN_ENVIO":     "segredo-envio-nao-pode-vazar",
			"ZAPGW_SEGREDO_ENTREGA": "segredo-entrega-nao-pode-vazar",
		}
		for k, v := range secrets {
			vars[k] = v
		}

		var out bytes.Buffer
		if err := dispatch(instanceArgs("lojinha"), &out, fakeEnvironment(vars)); err != nil {
			t.Fatalf("dispatch: %v", err)
		}

		for name, value := range secrets {
			if strings.Contains(out.String(), value) {
				t.Errorf("o valor de %s apareceu na saida do comando", name)
			}
		}
	})

	t.Run("segredos sorteados pelo comando", func(t *testing.T) {
		// The values are not known ahead of time: they are read BACK
		// from the database and searched for in the output. It is the
		// only way to cover the branch that names the generated ones,
		// which is exactly where the value would be at hand.
		//
		// ONLY THE TWO NON-SHARED ONES, per T-052 (see the test's
		// comment). The other two have their OWN test requiring the
		// opposite — printing —, and it is that pair of tests that keeps
		// the exception from becoming the rule or the rule from
		// swallowing the exception.
		vars := testEnvironment(t)

		var out bytes.Buffer
		if err := dispatch(instanceArgs("lojinha"), &out, fakeEnvironment(vars)); err != nil {
			t.Fatalf("dispatch: %v", err)
		}

		i, err := storeFromEnvironment(t, vars).FindInstance("lojinha")
		if err != nil {
			t.Fatalf("FindInstance: %v", err)
		}
		drawn := map[string]string{
			"ZAPGW_APP_SECRET":  i.AppSecret,
			"ZAPGW_TOKEN_ENVIO": i.SendToken,
		}
		for name, value := range drawn {
			if value == "" {
				t.Fatalf("%s ficou vazio no banco — o teste procuraria a string vazia e passaria sem verificar nada", name)
			}
			if strings.Contains(out.String(), value) {
				t.Errorf("o valor sorteado de %s apareceu na saida do comando", name)
			}
		}
	})
}

func TestProvisionInstanceGeneratesTheMissingSecretsAndSaysWHICH(t *testing.T) {
	// Naming the generated ones is what stops the operator from walking
	// away thinking their own app_secret was used when it was actually
	// generated — and inbound would then reject Meta's HMAC with no one
	// understanding why.
	vars := testEnvironment(t)
	vars["ZAPGW_TOKEN_ENVIO"] = "token-envio-de-teste" // this one came in; the other three didn't

	var out bytes.Buffer
	if err := dispatch(instanceArgs("lojinha"), &out, fakeEnvironment(vars)); err != nil {
		t.Fatalf("dispatch: %v", err)
	}

	text := out.String()
	// The "sorteados aqui (o valor NAO e mostrado)" line only talks
	// about the non-shared ones since T-052; the other two show up in
	// their own block, WITH the value — and the question the operator
	// has ("did the gateway use mine or generate one?") stays answered
	// for all four, just in two places with different consequences.
	if !strings.Contains(text, "ZAPGW_APP_SECRET") {
		t.Errorf("a saida nao diz que ZAPGW_APP_SECRET foi gerado:\n%s", text)
	}
	for _, field := range []string{"verify_token: ", "segredo_entrega: "} {
		if !strings.Contains(text, field) {
			t.Errorf("a saida nao entrega o %q que ela sorteou:\n%s", field, text)
		}
	}
	// "ZAPGW_TOKEN_ENVIO" came from the environment: it cannot appear
	// anywhere in the output, not even as a name.
	if strings.Contains(text, "ZAPGW_TOKEN_ENVIO") {
		t.Errorf("a saida diz que ZAPGW_TOKEN_ENVIO foi gerado, mas ele veio do ambiente:\n%s", text)
	}

	// Generated cannot be empty: a blank app_secret would make inbound
	// accept an HMAC over an empty secret instead of failing closed.
	i, err := storeFromEnvironment(t, vars).FindInstance("lojinha")
	if err != nil {
		t.Fatalf("FindInstance: %v", err)
	}
	if len(i.AppSecret) != 64 || len(i.VerifyToken) != 64 || len(i.DeliverySecret) != 64 {
		t.Errorf("segredo gerado nao tem 32 bytes em hex: app=%d verify=%d entrega=%d",
			len(i.AppSecret), len(i.VerifyToken), len(i.DeliverySecret))
	}
}

